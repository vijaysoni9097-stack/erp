import assert from 'node:assert/strict';
import { countryFromPhone, resolveCurrency } from '../src/services/currency.js';
const suppliers = ['9876543210', '8765432109', '7654321098', '+44 7700 900123'].map(phone => ({ phone }));
assert.equal(resolveCurrency({}, suppliers).currency, 'INR');
assert.equal(resolveCurrency({ country: 'United States', phone: '+1-555-0100' }, suppliers).currency, 'INR');
assert.equal(resolveCurrency({ country: 'United Kingdom', phone: '+91 9876543210' }).currency, 'GBP');
assert.equal(resolveCurrency({ phone: '+44 7700 900123' }).currency, 'GBP');
assert.equal(resolveCurrency({ country: 'CA' }).currency, 'CAD');
assert.equal(resolveCurrency({ country: 'Japan' }).formatMoney(18420), '¥18,420');
assert.equal(resolveCurrency({ country: 'India' }).formatMoney(18420), '₹18,420.00');
assert.equal(resolveCurrency({ country: 'India' }).formatMoney(1234567.5), '₹12,34,567.50');
assert.equal(resolveCurrency({ country: 'Kuwait' }).formatMoney(1.234).includes('1.234'), true);
assert.equal(countryFromPhone('0091 98765 43210'), 'IN');
assert.equal(countryFromPhone('+1-555-0100'), null);
assert.equal(countryFromPhone('+1 416 555 0123'), null);
assert.equal(countryFromPhone('9876543210'), null);
assert.equal(countryFromPhone('+91 123'), null);
assert.equal(countryFromPhone('not a phone'), null);
assert.equal(resolveCurrency({}, [{ phone: '+44 7700 900123' }]).currency, 'INR');
assert.equal(resolveCurrency().currency, 'INR');
assert.equal(resolveCurrency({ phone: '+971 50 123 4567' }).currency, 'AED');
console.log('Currency checks passed: supplier majority, profile fallback, phone prefixes, ambiguity, formatting and decimal precision.');
