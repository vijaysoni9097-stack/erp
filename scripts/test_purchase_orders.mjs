import assert from 'node:assert/strict';
import { purchaseDraftTotal, purchasePayload, purchaseLineTotal, purchaseOrderNumber } from '../src/services/purchaseOrders.js';
const items = [{ medicine_id: 1, quantity: '3', unit_price: '12.35' }, { medicine_id: 2, quantity: '2', unit_price: '0.10' }];
assert.equal(purchaseDraftTotal(items), 37.25);
assert.equal(purchaseOrderNumber(1), 'PO-000001');
assert.equal(purchaseLineTotal({ quantity: '1', unit_price: '0' }), 0);
const draft = { request_id: 'test-id', supplier_id: '3', expected_delivery: '', notes: '  deliver safely  ', items };
const payload = purchasePayload(draft, 'INR');
assert.equal(payload.supplier_id, 3);
assert.equal(payload.expected_delivery, null);
assert.equal(payload.notes, 'deliver safely');
assert.equal(payload.request_id, draft.request_id);
assert.deepEqual(payload.items[0], { medicine_id: 1, quantity: 3, unit_price: '12.35' });
for (const item of [{ quantity: '0', unit_price: '2' }, { quantity: '1.5', unit_price: '2' }, { quantity: '1', unit_price: '-1' }, { quantity: '1', unit_price: '1.001' }, { quantity: '1', unit_price: '' }, { quantity: '2147483647', unit_price: '9999999999.99' }]) assert.throws(() => purchaseLineTotal(item));
assert.throws(() => purchasePayload({ ...draft, items: [] }, 'INR'));
assert.throws(() => purchasePayload({ ...draft, supplier_id: '' }, 'INR'));
assert.throws(() => purchasePayload(draft, '…'));
assert.throws(() => purchasePayload({ ...draft, items: [items[0], items[0]] }, 'INR'));
console.log('Purchase order checks passed: exact totals, validation, duplicate items and retry reference.');
