import assert from 'node:assert/strict';
import {refreshDashboard} from '../src/services/dashboardRefresh.js';
const controller=new AbortController();
let release;const waiting=new Promise(resolve=>{release=resolve;});
const published=[];
const task=refreshDashboard({get:path=>path==='/credits/summary'?waiting:Promise.resolve({data:[]})},controller.signal,r=>published.push(r));
await new Promise(resolve=>setImmediate(resolve));
assert.equal(published.length,1,'Core dashboard must load before credit responds');
assert.equal(published[0].creditCollectionsPending,true);
release({data:{collections:{cash:20}}});
assert.equal(await task,'');assert.equal(published[1].creditCollections.cash,20);
assert.equal(published[1].creditCollectionsAvailable,true);
const failures=[];
const warning=await refreshDashboard({get:path=>path==='/credits/summary'?Promise.reject(new Error('timeout')):Promise.resolve({data:[]})},controller.signal,r=>failures.push(r));
assert.equal(failures.length,2);assert.ok(Array.isArray(failures[1].medicines));
assert.equal(failures[1].creditCollectionsAvailable,false);assert.ok(warning.includes('repayment'));
const aborted=new AbortController();aborted.abort();let calls=0;
await refreshDashboard({get:()=>Promise.resolve({data:[]})},aborted.signal,()=>calls++);assert.equal(calls,0);
console.log('Dashboard refresh checks passed: core data loads independently, credit timeout is explicit, repayments included, aborted loads ignored.');
